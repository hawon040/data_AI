/** 이번 달(1~12) 사진의 위치. 그 달 사진이 없으면 첫 사진. */
export function heroSlideIndexForMonth(month: number): number {
  return Math.max(
    HERO_SLIDES.findIndex((slide) => slide.month === month),
    0,
  );
}

/** 모션 줄이기 설정을 켰는지. 켰으면 사진을 자동으로 넘기지 않는다. */
export function prefersReducedMotion(): boolean {
  return typeof window !== "undefined" && window.matchMedia?.("(prefers-reduced-motion: reduce)").matches === true;
}
